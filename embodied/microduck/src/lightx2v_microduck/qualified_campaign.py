def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("command", choices=("collect", "merge", "audit", "dagger"))
    parser.add_argument("--output")
    parser.add_argument("--gate")
    parser.add_argument("--task", choices=tuple(training_contracts()))
    parser.add_argument("--episodes", type=int)
    parser.add_argument("--seed", type=int)
    parser.add_argument("--asset-root")
    parser.add_argument("--image-size", type=int, default=256)
    parser.add_argument("--indices", nargs="+")
    parser.add_argument("--index")
    parser.add_argument("--cache-dir")
    parser.add_argument("--checkpoint")
    parser.add_argument("--backbone")
    parser.add_argument("--device", default="cuda")
    parser.add_argument("--teacher-rollin-probability", type=float, default=0.)
    parser.add_argument("--teacher-prefix-ticks", type=int, default=0,
                        help="Fixed teacher execution prefix before student collection; DAgger only")
    args = parser.parse_args()
    if args.command != "dagger" and (args.teacher_rollin_probability != 0. or args.teacher_prefix_ticks != 0):
        parser.error("teacher roll-in applies only to DAgger collection")
    if args.command in ("collect", "dagger"):
        if not all((args.output, args.gate, args.task)):
            parser.error("collection requires --output, --gate and --task")
        kwargs = dict(episodes=args.episodes or (200 if args.command == "collect" else 100), seed=args.seed if args.seed is not None else (10000 if args.command == "collect" else 1000000), asset_root=args.asset_root, image_size=args.image_size)
        if args.command == "collect":
            result = collect(args.output, args.gate, args.task, **kwargs)
        else:
            if not args.checkpoint or not args.backbone:
                parser.error("DAgger requires --checkpoint and --backbone")
            from lightx2v.models.networks.tinyvla.runtime import MicroDuckTinyVLAPolicy, TinyVLARuntime
            runtime = TinyVLARuntime.from_directory(args.checkpoint, backbone_path=args.backbone, device=args.device, precision="bf16")
            result = dagger(args.output, args.gate, args.task, MicroDuckTinyVLAPolicy(runtime),
                            teacher_rollin_probability=args.teacher_rollin_probability,
                            teacher_prefix_ticks=args.teacher_prefix_ticks, **kwargs)
    elif args.command == "merge":
        if not args.output or not args.indices:
            parser.error("merge requires --output and --indices")
        result = merge(args.output, args.indices)
    else:
        if not args.index:
            parser.error("audit requires --index")
        result = audit(args.index, asset_root=args.asset_root, cache_dir=args.cache_dir)
    print(json.dumps({"command": args.command, "episodes": len(result["episodes"]) if isinstance(result.get("episodes"), list) else result.get("episodes"), "output": args.output or args.index}, indent=2))


if __name__ == "__main__":
    main()
